"""Generate docs/reference/tools.md from the MCP server's tool definitions.

Run from the repository root:  python scripts/generate_tool_reference.py
The page is built from the source of src/tess_memory/server.py without
importing it, so no store or provider is touched.
"""
from __future__ import annotations

import ast
import inspect
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SERVER = ROOT / "src" / "tess_memory" / "server.py"
OUT = ROOT / "docs" / "reference" / "tools.md"

GROUPS = [
    ("Recall", ["get_project_context", "search_memory", "recent_activity", "get_session", "get_session_transcript", "list_projects"]),
    ("Plan", ["plan_add", "plan_update", "plan_board", "plan_get"]),
    ("Share and inspect", ["memory_share", "memory_status"]),
]


CONSTANTS = {"DEFAULT_PAGE_BYTES": "12000"}  # transcript_reader.py; pages may be 256 to 24000 bytes

# Meanings for arguments whose description is built from constants at import time.
NOTES = {
    ("get_session_transcript", "max_bytes"): "Maximum source bytes in this page. A page may be slightly smaller so that it ends on a character boundary.",
}


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _description(annotation: ast.expr | None) -> str:
    """The Field(description=...) text inside an Annotated[...] annotation."""
    if annotation is None:
        return ""
    for node in ast.walk(annotation):
        if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "Field":
            for keyword in node.keywords:
                if keyword.arg == "description":
                    try:
                        return str(ast.literal_eval(keyword.value))
                    except ValueError:
                        return ""  # built from constants at import time
    return ""


def _type(annotation: ast.expr | None) -> str:
    if annotation is None:
        return ""
    if isinstance(annotation, ast.Subscript) and getattr(annotation.value, "id", "") == "Annotated":
        inner = annotation.slice.elts[0] if isinstance(annotation.slice, ast.Tuple) else annotation.slice
        return ast.unparse(inner)
    return ast.unparse(annotation)


def main() -> None:
    tree = ast.parse(SERVER.read_text())
    tools = {
        node.name: node
        for node in tree.body
        if isinstance(node, ast.FunctionDef) and any("tool" in ast.unparse(d) for d in node.decorator_list)
    }
    listed = [name for _, names in GROUPS for name in names]
    missing, unlisted = set(listed) - set(tools), set(tools) - set(listed)
    if missing or unlisted:
        raise SystemExit(f"Tool groups are out of date. Missing: {sorted(missing)}; not grouped: {sorted(unlisted)}")

    lines = [
        "# MCP tool reference",
        "",
        "<!-- Generated by scripts/generate_tool_reference.py. Do not edit by hand. -->",
        "",
        f"The {len(tools)} tools the Tess Memory server offers an agent. The descriptions below are",
        "the ones the agent itself reads. Every `project` argument accepts a project key from",
        "`list_projects`, or an absolute path for a project named after its working directory.",
        "",
    ]
    for title, names in GROUPS:
        lines += [f"## {title}", ""]
        for name in names:
            node = tools[name]
            doc = inspect.cleandoc(ast.get_docstring(node) or "")
            lines += [f"### `{name}`", "", doc, ""]
            arguments = node.args.args
            if arguments:
                defaults = [None] * (len(arguments) - len(node.args.defaults)) + list(node.args.defaults)
                lines += ["| Argument | Type | Default | Meaning |", "|---|---|---|---|"]
                for argument, default in zip(arguments, defaults):
                    shown = "required" if default is None else f"`{CONSTANTS.get(ast.unparse(default), ast.unparse(default))}`"
                    meaning = _description(argument.annotation) or NOTES.get((name, argument.arg), "")
                    lines.append(f"| `{argument.arg}` | `{_cell(_type(argument.annotation))}` | {shown} | {_cell(meaning)} |")
                lines.append("")
            else:
                lines += ["Takes no arguments.", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines).rstrip() + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
